flipped = {}  # (raw_idx, flip_combo) -> count

for r, row in enumerate(TMX_DATA):
    for c, gid in enumerate(row):
        if gid == 0:
            continue
        flags = gid & FLIP_MASK
        if flags == 0:
            continue
        raw = gid & ~FLIP_MASK
        idx = raw - FIRSTGID
        tile_row = idx // COLS
        tile_col = idx % COLS
        
        h = bool(gid & FLIP_H)
        v = bool(gid & FLIP_V)
        d = bool(gid & FLIP_D)
        
        combo = ""
        if h: combo += "H"
        if v: combo += "V"
        if d: combo += "D"
        
        key = (tile_row, tile_col, combo)
        if key not in flipped:
            flipped[key] = {"count": 0, "positions": [], "gid": gid}
        flipped[key]["count"] += 1
        flipped[key]["positions"].append((r, c))

print(f"=== 翻转瓦片分析 ===")
print(f"总数: {len(flipped)} 种不同的翻转组合\n")

for (tr, tc, combo), info in sorted(flipped.items()):
    tile_name = f"tile_r{tr:02d}_c{tc:02d}"
    print(f"  {tile_name}  翻转={combo:3s}  出现{info['count']}次  GID={info['gid']}  位置={info['positions'][:3]}{'...' if info['count'] > 3 else ''}")

